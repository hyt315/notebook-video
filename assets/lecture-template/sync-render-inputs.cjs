const fs = require('node:fs');
const path = require('node:path');

const root = __dirname;
const pairs = [
  ['audio/narration.mp3', 'public/narration.mp3'],
  ['manifests/caption-cues.json', 'src/caption-cues.json'],
];
for (const [from, to] of pairs) {
  const source = path.join(root, from);
  const target = path.join(root, to);
  if (!fs.existsSync(source) || fs.statSync(source).size === 0) {
    throw new Error(`Required render input is missing or empty: ${source}`);
  }
  fs.mkdirSync(path.dirname(target), {recursive: true});
  fs.copyFileSync(source, target);
  if (!fs.readFileSync(source).equals(fs.readFileSync(target))) {
    throw new Error(`Render input sync failed: ${from} -> ${to}`);
  }
}
console.log('Synchronized canonical render inputs into public/ and src/.');

// 3.5.0 · 声音配置：默认无 BGM。只有 manifests/treatment.json 明确写 sound.music.use=true 才加载音乐床。
// 生成 src/audio-config.ts 而不是让 TSX 去读 manifests：渲染包只认 src/ 下的静态 import。
const treatmentPath = path.join(root, 'manifests', 'treatment.json');
let music = false;
if (fs.existsSync(treatmentPath)) {
  try {
    const t = JSON.parse(fs.readFileSync(treatmentPath, 'utf8'));
    music = t?.sound?.music?.use === true;
  } catch (e) {
    throw new Error(`manifests/treatment.json 不是合法 JSON：${e.message}`);
  }
}
fs.writeFileSync(
  path.join(root, 'src', 'audio-config.ts'),
  '// AUTO-GENERATED by sync-render-inputs.cjs from manifests/treatment.json — 禁止手改。\n'
  + `// 默认无 BGM：treatment.sound.music.use 不是 true（或没有 treatment）时为 false。\n`
  + `export const MUSIC_ON = ${music};\n`
);
console.log(`Sound config: music ${music ? 'ON (treatment.sound.music.use=true)' : 'OFF (default)'}.`);

// 3.6.0 · 素材表：src/media.json 是渲染包里唯一被读的那份（craft/media.tsx 的 MEDIA）。
// 以前没人同步它，于是 manifests/media.json 加了素材、画面照样报
// 「manifests/media.json 里没有 id=…」——素材在，图出不来。
const mediaSrc = path.join(root, 'manifests', 'media.json');
const mediaOut = path.join(root, 'src', 'media.json');
if (fs.existsSync(mediaSrc)) {
  const raw = fs.readFileSync(mediaSrc, 'utf8');
  try {
    JSON.parse(raw);
  } catch (e) {
    throw new Error(`manifests/media.json 不是合法 JSON：${e.message}`);
  }
  const before = fs.existsSync(mediaOut) ? fs.readFileSync(mediaOut, 'utf8') : '';
  if (before !== raw) {
    fs.writeFileSync(mediaOut, raw);
    const n = (JSON.parse(raw).items || []).length;
    console.log(`Media: synced ${n} item(s) from manifests/media.json → src/media.json.`);
  }
}
