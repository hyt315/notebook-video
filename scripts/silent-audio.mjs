// 静音旁白占位：make-video --stills / preview 共用的那一条 ffmpeg。
// 3.5.0 起「成片必须有真实旁白」，静音占位只许给看画面用（见 make-video.mjs 的 requireNarrationForRender）。
// 抽出来是为了让 preview 与 --stills 用的是**同一条**命令，不再各写一份。
import {spawnSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

export const SILENT_MARKER = 'generated by make-video --stills\n';

/** 已有真实旁白就绝不动它；没有才写静音占位。返回是否真的生成了。 */
export function writeSilentNarration(project, secs) {
  const narr = path.join(project, 'audio', 'narration.mp3');
  if (fs.existsSync(narr)) return false;
  fs.mkdirSync(path.join(project, 'audio'), {recursive: true});
  const r = spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'lavfi',
    '-i', 'anullsrc=r=48000:cl=mono', '-t', String(secs), '-c:a', 'libmp3lame', '-b:a', '64k', narr]);
  if (r.status !== 0) {
    console.error('ffmpeg 不可用：请安装 ffmpeg 并放进 PATH');
    process.exit(1);
  }
  fs.writeFileSync(path.join(project, 'audio', '.silent-placeholder'), SILENT_MARKER);
  return true;
}
