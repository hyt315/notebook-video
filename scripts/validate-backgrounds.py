#!/usr/bin/env python3
"""validate-backgrounds.py · 背景库门禁（3.4.0）。

两种用法：

  # 1. 库本身（模板或工程里的 manifests/backgrounds.json）：每张图都有来源与许可、文件在、sha256 对、
  #    亮底、字幕区对比度够、中央够安静。CI / validate-skill 跑模板；工程里改了库也该跑。
  python scripts/validate-backgrounds.py PROJECT_OR_TEMPLATE_DIR [--min-per-skin journal=8,…]

  # 2. 工程的分镜结果（manifests/shots.resolved.json）：每镜的背景存在、属于当前皮肤、相邻两镜不重复（P1 提示）。
  python scripts/validate-backgrounds.py PROJECT_DIR --shots

只用标准库；指标（亮度 / 对比度 / 中央起伏）在生成时由 scripts/dev/make-bg-library.py 算好写进 manifest，
并和 sha256 绑定——文件变了 sha 就对不上。维护者可用 scripts/dev/bg_metrics.py（numpy + pillow）按同一算法重算比对（unittest 会跑）。

判据（交付分辨率 2560×1440；字幕区 = 字幕实际落点外扩一圈：x 391–2169，y 1236–1404）：
  P0  manifest 缺字段 / 文件缺失 / sha256 不符 / 许可不在白名单 / CC BY 缺署名或来源链接 / 皮肤未知
  P0  亮底：整幅平均相对亮度 < 0.55
  P0  字幕区：皮肤墨色 vs 字幕区平均亮度 < 7:1，或 vs 字幕区最暗 5 %（4 px 模糊后）< 4.5:1
      ——按「字幕衬底不存在」来量（journal 本来就没有衬底；其余皮肤有衬底，这条是保底）
  P1  中央 70 % 起伏（1/8 降采样后亮度标准差）> 0.05：背景会和内容抢
  P1  分镜相邻两镜同一张背景（--shots）
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

SKINS = ("flat", "cel", "journal", "papercut", "archive")
ROLES = ("main", "chapter", "quiet")
# 皮肤墨色（= src/theme/<skin>.tsx 的 palette.ink；validate-skill-consistency 会核对两边一致）
INK = {"flat": "#1c2024", "cel": "#111111", "journal": "#2b2420", "papercut": "#2a1a14", "archive": "#1d2328"}
LICENSES = {
    "PD": "public domain",
    "CC0-1.0": "CC0 1.0",
    "CC-BY-2.0": "CC BY 2.0", "CC-BY-3.0": "CC BY 3.0", "CC-BY-4.0": "CC BY 4.0",
    "Apache-2.0": "generated by this repository (Apache-2.0)",
}
SOURCE_KINDS = ("procedural", "paper-shaders", "commons", "ai-generated")
W, H = 2560, 1440
ZONE = (391, 1236, 2169, 1404)          # 字幕区（x0, y0, x1, y1）
CENTRE = (384, 216, 2176, 1224)         # 中央 70 %
MIN_MEAN_LUM = 0.55
MIN_ZONE_MEAN = 7.0
MIN_ZONE_P05 = 4.5
MAX_CENTRE_STD = 0.05


def rel_lum_rgb(r: float, g: float, b: float) -> float:
    def c(v: float) -> float:
        v = v / 255.0
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    return 0.2126 * c(r) + 0.7152 * c(g) + 0.0722 * c(b)


def hex_lum(h: str) -> float:
    h = h.lstrip("#")
    return rel_lum_rgb(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


def contrast(l1: float, l2: float) -> float:
    a, b = max(l1, l2), min(l1, l2)
    return (a + 0.05) / (b + 0.05)


def judge_metrics(skin: str, m: dict) -> tuple[list[str], list[str]]:
    p0, p1 = [], []
    if m.get("size") != [W, H]:
        return [f"尺寸 {m.get('size')} ≠ {W}×{H}"], p1
    ink = hex_lum(INK[skin])
    if m["mean_lum"] < MIN_MEAN_LUM:
        p0.append(f"不是亮底：平均相对亮度 {m['mean_lum']:.3f} < {MIN_MEAN_LUM}")
    cm, cp = contrast(ink, m["zone_mean_lum"]), contrast(ink, m["zone_p05_lum"])
    if cm < MIN_ZONE_MEAN:
        p0.append(f"字幕区对比度不足：墨色 vs 字幕区平均 {cm:.1f}:1 < {MIN_ZONE_MEAN}:1")
    if cp < MIN_ZONE_P05:
        p0.append(f"字幕区有深色装饰：墨色 vs 字幕区最暗 5 % {cp:.1f}:1 < {MIN_ZONE_P05}:1")
    if m["centre_std"] > MAX_CENTRE_STD:
        p1.append(f"中央 70 % 起伏 {m['centre_std']:.3f} > {MAX_CENTRE_STD}：背景可能和内容抢")
    return p0, p1


def load_library(root: Path) -> dict:
    p = root / "manifests" / "backgrounds.json"
    if not p.is_file():
        raise FileNotFoundError(p)
    return json.loads(p.read_text(encoding="utf-8"))


def check_library(root: Path, min_per_skin: dict | None = None) -> tuple[list[str], list[str]]:
    doc = load_library(root)
    p0, p1 = [], []
    entries = doc.get("backgrounds")
    if not isinstance(entries, list) or not entries:
        return ["backgrounds.json 必须有非空 backgrounds 数组"], p1
    seen = set()
    count: dict[str, int] = {}
    for e in entries:
        eid = e.get("id", "?")
        tag = f"[{eid}]"
        for k in ("id", "skin", "file", "name", "roles", "source", "license", "attribution", "sha256", "metrics"):
            if k not in e or e[k] in (None, "", []):
                p0.append(f"{tag} 缺字段 {k}")
        if eid in seen:
            p0.append(f"{tag} id 重复")
        seen.add(eid)
        skin = e.get("skin")
        if skin not in SKINS:
            p0.append(f"{tag} 皮肤 {skin!r} 未知（{'/'.join(SKINS)}）")
            continue
        if not str(eid).startswith(f"{skin}/"):
            p0.append(f"{tag} id 必须以 '{skin}/' 开头")
        bad_roles = [r for r in e.get("roles") or [] if r not in ROLES]
        if bad_roles:
            p0.append(f"{tag} roles 含未知角色 {bad_roles}")
        lic = e.get("license")
        if lic not in LICENSES:
            p0.append(f"{tag} 许可 {lic!r} 不在白名单（{', '.join(LICENSES)}）；BY-SA / NC / ND / 未知一律不收")
        src = e.get("source") or {}
        kind = src.get("kind")
        if kind not in SOURCE_KINDS:
            p0.append(f"{tag} source.kind {kind!r} 不在 {SOURCE_KINDS}")
        if kind == "commons":
            for k in ("title", "url", "author", "license_as_published"):
                if not src.get(k):
                    p0.append(f"{tag} Commons 来源缺 source.{k}")
        if kind == "paper-shaders" and not src.get("package"):
            p0.append(f"{tag} Paper Shaders 来源缺 source.package（锁版本）")
        if kind in ("procedural", "paper-shaders") and not src.get("generator"):
            p0.append(f"{tag} 缺 source.generator（生成脚本路径）")
        if str(lic).startswith("CC-BY") and not (e.get("attribution") and src.get("url")):
            p0.append(f"{tag} CC BY 必须署名（attribution）并给来源链接（source.url）")
        f = root / str(e.get("file", ""))
        if not f.is_file():
            p0.append(f"{tag} 文件不存在：{e.get('file')}")
            continue
        if not str(e.get("file", "")).startswith("public/"):
            p0.append(f"{tag} file 必须在 public/ 下（staticFile 才取得到）")
        sha = hashlib.sha256(f.read_bytes()).hexdigest()
        if sha != e.get("sha256"):
            p0.append(f"{tag} sha256 不符（文件被改过却没重跑 make-bg-library.py --register）")
        m = e.get("metrics") or {}
        if {"mean_lum", "zone_mean_lum", "zone_p05_lum", "centre_std"} <= set(m):
            a, b = judge_metrics(skin, dict(m, size=m.get("size", [W, H])))
            p0 += [f"{tag} {x}" for x in a]
            p1 += [f"{tag} {x}" for x in b]
        if not e.get("legacy"):
            count[skin] = count.get(skin, 0) + 1
        count.setdefault(skin, 0)
    for skin, need in (min_per_skin or {}).items():
        if count.get(skin, 0) < need:
            p0.append(f"皮肤 {skin} 只有 {count.get(skin, 0)} 张库背景（不含 legacy main/chapter/quiet），至少要 {need} 张")
    # 每个皮肤每种角色至少一张（自动轮换要有得挑）
    for skin in count:
        for role in ROLES:
            if not any(e.get("skin") == skin and role in (e.get("roles") or []) for e in entries):
                p1.append(f"皮肤 {skin} 没有任何一张能做 {role} 角色的背景（自动轮换会退回到本皮肤全部背景里挑）")
    return p0, p1


def check_shots(root: Path) -> tuple[list[str], list[str]]:
    p0, p1 = [], []
    rp = root / "manifests" / "shots.resolved.json"
    if not rp.is_file():
        return [f"缺 {rp}（先跑 resolve-shots）"], p1
    res = json.loads(rp.read_text(encoding="utf-8"))
    theme = res.get("theme")
    try:
        lib = {e["id"]: e for e in load_library(root).get("backgrounds", [])}
    except FileNotFoundError:
        lib = {}
    prev = None
    for s in res.get("shots", []):
        bg = s.get("bgFile") or (f"legacy:{s['bg']}" if s.get("bg") in ROLES else None)
        bid = s.get("bg")
        if bid and bid not in ROLES:
            e = lib.get(bid)
            if e is None:
                p0.append(f"{s['id']}: 背景 {bid!r} 不在 manifests/backgrounds.json")
            elif e.get("skin") != theme:
                p0.append(f"{s['id']}: 背景 {bid!r} 属于 {e.get('skin')} 皮肤，当前皮肤是 {theme}")
        if bg and prev and bg == prev[1]:
            p1.append(f"{s['id']}: 与上一镜 {prev[0]} 用同一张背景 {bid}（相邻镜重复：换一张，或去掉显式 bg 让引擎轮换）")
        prev = (s["id"], bg) if bg else None
    return p0, p1


def parse_min(spec: str) -> dict:
    out = {}
    for part in filter(None, (spec or "").split(",")):
        k, v = part.split("=")
        out[k.strip()] = int(v)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root")
    ap.add_argument("--shots", action="store_true", help="检查工程分镜的背景分配（相邻重复、皮肤一致）")
    ap.add_argument("--min-per-skin", default="", help="如 journal=8,papercut=8,archive=8,flat=4,cel=4（只数新增的库背景，不含 legacy 三张）")
    a = ap.parse_args()
    root = Path(a.root).resolve()
    if a.shots:
        p0, p1 = check_shots(root)
        label = "背景分配"
    else:
        try:
            p0, p1 = check_library(root, parse_min(a.min_per_skin))
        except FileNotFoundError as e:
            print(f"validate-backgrounds：没有背景库 {e}（3.4.0 之前的工程：按 main/chapter/quiet 三张图渲染，不受影响）")
            return 0
        label = "背景库"
    for x in p0:
        print(f"  P0 {x}", file=sys.stderr)
    for x in p1:
        print(f"  P1 {x}")
    if p0:
        print(f"validate-backgrounds：{label} 未通过（P0 {len(p0)}，P1 {len(p1)}）", file=sys.stderr)
        return 1
    print(f"validate-backgrounds：{label} 通过（P0 0，P1 {len(p1)}）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
