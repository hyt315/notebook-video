#!/usr/bin/env python3
"""3.7.0: storyboard.md is generated from the real shot table (shots.resolved.json) by resolve-shots."""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TPL = ROOT / "assets" / "lecture-template"
RS = ROOT / "scripts" / "resolve-shots.py"


def project(storyboard: str | None = None, treatment: dict | None = None) -> Path:
    d = Path(tempfile.mkdtemp(prefix="nv-sb-"))
    (d / "manifests").mkdir()
    (d / "src").mkdir()
    for f in ("caption-cues.json", "shots.json"):
        shutil.copy(TPL / "manifests" / f, d / "manifests" / f)
    if storyboard is not None:
        (d / "storyboard.md").write_text(storyboard, encoding="utf-8")
    if treatment is not None:
        (d / "manifests" / "treatment.json").write_text(json.dumps(treatment, ensure_ascii=False), encoding="utf-8")
    return d


def resolve(d: Path) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(RS), str(d)], capture_output=True, text=True, encoding="utf-8")


def rows(md: str) -> list[list[str]]:
    out = []
    for line in md.splitlines():
        if re.match(r"\|\s*S\d", line):
            out.append([c.strip() for c in line.strip().strip("|").split("|")])
    return out


class StoryboardTest(unittest.TestCase):
    def test_matches_resolved_shot_table(self):
        d = project()
        self.assertEqual(resolve(d).returncode, 0)
        res = json.loads((d / "manifests" / "shots.resolved.json").read_text(encoding="utf-8"))
        md = (d / "storyboard.md").read_text(encoding="utf-8")
        r = rows(md)
        self.assertEqual(len(r), len(res["shots"]))
        for row, s in zip(r, res["shots"]):
            self.assertEqual(row[0], s["id"])
            self.assertEqual(row[1], f"{s['from'] / 30:.2f}–{s['to'] / 30:.2f}")
        self.assertIn(f"总帧数 {res['duration']}", md)
        self.assertIn(f"{res['duration'] / 30:.1f} 秒", md)
        self.assertIn("皮肤 ", md)

    def test_overwrites_when_marked(self):
        d = project(storyboard="<!-- AUTO-GENERATED by resolve-shots -->\nold\n")
        self.assertEqual(resolve(d).returncode, 0)
        md = (d / "storyboard.md").read_text(encoding="utf-8")
        self.assertNotIn("\nold\n", md)
        self.assertTrue(md.startswith("<!-- AUTO-GENERATED by resolve-shots"))
        self.assertFalse((d / "storyboard.generated.md").exists())

    def test_old_template_example_is_replaced(self):
        d = project(storyboard="# 时间码分镜：GitHub 开源三部曲 EP0（官方模板示例片）\n\nstale\n")
        self.assertEqual(resolve(d).returncode, 0)
        self.assertNotIn("stale", (d / "storyboard.md").read_text(encoding="utf-8"))

    def test_hand_written_is_kept(self):
        d = project(storyboard="# my own storyboard\n")
        r = resolve(d)
        self.assertEqual(r.returncode, 0)
        self.assertEqual((d / "storyboard.md").read_text(encoding="utf-8"), "# my own storyboard\n")
        self.assertTrue((d / "storyboard.generated.md").is_file())
        self.assertIn("storyboard.generated.md", r.stderr)

    def test_intent_and_actual_zoom_columns_filled(self):
        for treatment in (None, {"topic": "测试片", "signature_shot": "S3", "shots": [{"id": "S1", "framing": "全", "move": "establish"}]}):
            d = project(treatment=treatment)
            self.assertEqual(resolve(d).returncode, 0)
            md = (d / "storyboard.md").read_text(encoding="utf-8")
            for row in rows(md):
                self.assertNotIn(row[4], ("", "—"), row)
                self.assertRegex(row[5], r"^\d\.\d\d→\d\.\d\d")
            if treatment:
                self.assertIn("# 分镜 · 测试片", md)
                self.assertIn("全：最松 ≤1.05", md)
                self.assertIn("招牌镜头 推≥12%", rows(md)[2][4])

    def test_check_mode_writes_nothing(self):
        d = project()
        subprocess.run([sys.executable, str(RS), str(d), "--check"], check=True, capture_output=True)
        self.assertFalse((d / "storyboard.md").exists())


if __name__ == "__main__":
    unittest.main()
